from pathlib import Path
from playwright.sync_api import sync_playwright, expect

ROOT = Path(__file__).parent
OUT = ROOT.parent / "artifacts/desktop-preview"
OUT.mkdir(parents=True, exist_ok=True)
with sync_playwright() as p:
    browser = p.chromium.launch(channel="msedge", headless=True, ignore_default_args=["--edge-skip-compat-layer-relaunch"])
    page = browser.new_page(viewport={"width": 1440, "height": 960})
    errors = []
    page.on("pageerror", lambda error: errors.append(str(error)))
    page.goto("http://127.0.0.1:18766", wait_until="domcontentloaded")
    expect(page.locator("#service")).to_have_text("本地服务已连接")
    page.wait_for_function("typeof restoreDone !== 'undefined' && restoreDone")
    page.locator('#view-workspace').click()
    page.locator('#tab-editor').click()
    page.evaluate('draft=[];edited();')
    page.locator('#editor-panel details summary').first.click()
    page.locator("#node-lat").fill("31.2304")
    page.locator("#node-lng").fill("121.4737")
    page.locator("#add-coordinate").click()
    page.locator("#node-lat").fill("31.2314")
    page.locator("#node-lng").fill("121.4750")
    page.locator("#add-coordinate").click()
    page.locator("#node-lat").fill("31.2321")
    page.locator("#node-lng").fill("121.4732")
    page.locator("#add-coordinate").click()
    page.locator("#route-name").fill("示例 · 街区短路线")
    page.locator("#fit").click()
    page.locator("#save-route").click()
    expect(page.locator("#name-dialog")).to_be_visible()
    page.locator('#name-dialog button[value="save"]').click()
    expect(page.locator("#memory-state")).to_have_text("已保存在这台电脑")
    page.wait_for_timeout(1500)
    page.screenshot(path=str(OUT / "01-路线工作台.png"))
    page.locator("#view-library").click()
    expect(page.locator(".route-card h3")).to_contain_text("街区短路线")
    page.screenshot(path=str(OUT / "02-路线库.png"))
    page.reload()
    expect(page.locator("#library-view")).to_be_visible()
    expect(page.locator(".route-card")).to_have_count(1)
    page.locator(".route-card-actions button").filter(has_text="载入回放").click()
    expect(page.locator("#player-panel")).to_be_visible()
    page.locator("#pace").fill("7")
    page.locator("#apply").click()
    page.locator("#save-preset").click()
    expect(page.locator("#name-dialog")).to_be_visible()
    page.locator("#name-input").fill("7 分钟 · 常用节奏")
    page.locator('#name-dialog button[value="save"]').click()
    expect(page.locator("#preset-select option")).to_have_count(2)
    page.locator('.inspector').evaluate('(element)=>element.scrollTop=0')
    page.screenshot(path=str(OUT / "03-手机回放.png"))
    page.locator("#view-history").click()
    page.screenshot(path=str(OUT / "04-回放历史.png"))
    page.set_viewport_size({"width": 1100, "height": 740})
    page.locator("#view-workspace").click()
    assert page.evaluate("document.documentElement.scrollWidth <= innerWidth")
    page.screenshot(path=str(OUT / "05-紧凑窗口.png"))
    assert not errors, errors
    browser.close()
print("PASS: desktop UI, route library, reload persistence, presets, empty history, minimum window; no device connection or location writes")
